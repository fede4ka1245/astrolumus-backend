def load_data(apps, schema_editor):
    TarotCard = apps.get_model("tarot", "TarotCard")
    TarotSpread = apps.get_model("tarot", "TarotSpread")

    # Major arcana
    for code, name, num, up, dn, kw in MAJOR_ARCANA:
        TarotCard.objects.update_or_create(
            code=code,
            defaults={
                "name": name,
                "arcana": "major",
                "suit": None,
                "number": num,
                "upright_meaning": up,
                "reversed_meaning": dn,
                "keywords": kw,
            },
        )

    # Minor arcana — pips + court for every suit.
    for suit_code, suit_ru, element, theme_up, theme_dn in SUITS:
        for num, rank_ru, up_tpl, dn_tpl in PIPS + COURT:
            code = f"{suit_code}_{num:02d}"
            name = f"{rank_ru} {suit_ru}"
            up = up_tpl.format(element=element, theme_up=theme_up, theme_dn=theme_dn)
            dn = dn_tpl.format(element=element, theme_up=theme_up, theme_dn=theme_dn)
            TarotCard.objects.update_or_create(
                code=code,
                defaults={
                    "name": name,
                    "arcana": "minor",
                    "suit": suit_code,
                    "number": num,
                    "upright_meaning": up,
                    "reversed_meaning": dn,
                    "keywords": [suit_ru.lower(), rank_ru.lower()],
                },
            )

    # Spreads
    for s in SPREADS:
        TarotSpread.objects.update_or_create(
            code=s["code"],
            defaults={
                "name": s["name"],
                "description": s["description"],
                "card_count": s["card_count"],
                "positions": s["positions"],
                "sort_order": s["sort_order"],
                "is_active": True,
            },
        )


