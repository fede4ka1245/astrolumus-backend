#!/bin/bash
set -e

TOLGEE_DB="${TOLGEE_DB_NAME:-tolgee}"
TOLGEE_USER="${TOLGEE_DB_USER:-tolgee}"
TOLGEE_PASS="${TOLGEE_DB_PASSWORD:-tolgee123}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    DO \$\$
    BEGIN
        IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '$TOLGEE_USER') THEN
            CREATE ROLE $TOLGEE_USER WITH LOGIN PASSWORD '$TOLGEE_PASS';
        END IF;
    END
    \$\$;

    SELECT 'CREATE DATABASE $TOLGEE_DB OWNER $TOLGEE_USER'
    WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '$TOLGEE_DB')\gexec

    GRANT ALL PRIVILEGES ON DATABASE $TOLGEE_DB TO $TOLGEE_USER;
EOSQL
